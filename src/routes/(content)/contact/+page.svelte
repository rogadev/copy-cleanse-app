<h1>Contact</h1>
<p class="text-slate-400">The best way to reach the maintainer, depending on what you need.</p>

<h2>Bug reports and feature requests</h2>
<p>
	Please open an issue on GitHub:
	<a href="https://github.com/rogadev/copy-cleanse/issues">github.com/rogadev/copy-cleanse/issues</a
	>. Include a sample of the text that's misbehaving and what browser you're on if it's a rendering
	bug.
</p>

<h2>Security reports</h2>
<p>
	If you think you've found a security issue, please do not open a public issue. Email
	<a href="mailto:ryan@roga.dev?subject=Copy%20Cleanse%20security">ryan@roga.dev</a> with a description
	and, if applicable, steps to reproduce.
</p>

<h2>Everything else</h2>
<p>
	General inquiries, partnership questions, press: email
	<a href="mailto:ryan@roga.dev">ryan@roga.dev</a>.
</p>

<h2>Response times</h2>
<p>
	Copy Cleanse is a solo project maintained in spare time. Expect responses within a few business
	days for most inquiries; security reports are prioritized.
</p>
